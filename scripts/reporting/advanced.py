    def _count_by_severity(self, findings: List[Dict[str, Any]]) -> Dict[str, int]:
        """Count findings by severity."""
        counts = {}
        for finding in findings:
            severity = finding.get('severity', 'unknown').lower()
            counts[severity] = counts.get(severity, 0) + 1
        return counts
    
    def _count_by_type(self, findings: List[Dict[str, Any]]) -> Dict[str, int]:
        """Count findings by type."""
        counts = {}
        for finding in findings:
            ftype = finding.get('type', 'unknown').lower()
            counts[ftype] = counts.get(ftype, 0) + 1
        return counts
    
    def _calculate_risk_rating(self, severity_counts: Dict[str, int]) -> str:
        """Calculate overall risk rating."""
        critical = severity_counts.get('critical', 0)
        high = severity_counts.get('high', 0)
        medium = severity_counts.get('medium', 0)
        
        if critical > 0:
            return "🔴 **CRITICAL**: The system has critical vulnerabilities that require immediate attention. These vulnerabilities can lead to complete system compromise, significant data breaches, or service disruption. Immediate remediation is strongly recommended."
        elif high > 0:
            return "🟠 **HIGH**: The system has high-severity vulnerabilities that pose significant security risks. These should be addressed within the next few weeks to prevent potential exploitation."
        elif medium > 0:
            return "🟡 **MEDIUM**: The system has medium-severity vulnerabilities that should be addressed as part of regular maintenance cycles. While not immediately critical, these findings represent real security risks."
        elif low > 0:
            return "🟢 **LOW**: The system has only low-severity findings. These represent minor security risks that should be addressed when convenient."
        else:
            return "🔵 **GOOD**: No significant security vulnerabilities were identified. The system appears to have a good security posture."
    
    def _severity_rank(self, severity: str) -> int:
        """Get rank of severity (higher = more severe)."""
        ranks = {
            'critical': 5,
            'high': 4,
            'medium': 3,
            'low': 2,
            'info': 1,
            'informational': 1
        }
        return ranks.get(severity, 0)
    
    def _filter_findings(self, findings: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Filter findings based on configuration."""
        filtered = findings
        
        # Filter by severity
        if self.config.severity_filter:
            filtered = [
                f for f in filtered 
                if f.get('severity', '').lower() in [s.lower() for s in self.config.severity_filter]
            ]
        
        # Filter by type
        if self.config.type_filter:
            filtered = [
                f for f in filtered 
                if f.get('type', '').lower() in [t.lower() for t in self.config.type_filter]
            ]
        
        # Filter by status
        if self.config.status_filter:
            filtered = [
                f for f in filtered 
                if f.get('verification', {}).get('status', '').lower() in [s.lower() for s in self.config.status_filter]
            ]
        
        return filtered
    
    def save_report(self, report: str, output_path: Union[str, Path], format: str = 'markdown') -> bool:
        """
        Save report to file.
        
        Args:
            report: Report content
            output_path: Output file path
            format: Report format
        
        Returns:
            True if save was successful
        """
        try:
            output_path = Path(output_path)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            
            # Determine file extension based on format
            if format == 'html':
                output_path = output_path.with_suffix('.html')
            elif format == 'json':
                output_path = output_path.with_suffix('.json')
            elif format == 'pdf':
                output_path = output_path.with_suffix('.pdf')
            else:  # markdown
                output_path = output_path.with_suffix('.md')
            
            # Write report
            with open(output_path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(report)
            
            return True
        except IOError:
            return False


